#!/usr/bin/env python3
"""zombiecheck.py -- the zombie bank, clip by clip, on a body that never owned one.

    python reva_native/anim_bench/zombiecheck.py [--body v1_Character_01]
                                                 [--secs 3] [--cols 6] [--clips a,b,c]

WHAT IT PROVES. v1_zmoves holds 32 ZAMN clips authored on the UE5 mannequin. None of the
105 town citizens has ever met that rig. Every clip therefore reaches a body through the
canonical transfer (donorPoseF), and a transfer that "loads without error" can still
produce a corpse standing in a T-pose -- the club has been fooled by exactly that before.
So each clip is played on a real citizen and LOOKED AT.

Rows are clips, columns are time -- the ridecheck.py shape, for the same reason: a pose
is a sample of something that is mostly not that pose, and one still cannot convict or
acquit an animation (the anim_verify_motion law).

HOW IT GETS A ROW PER CLIP OUT OF ONE LAUNCH. Booting the engine costs ~15s, so shooting
32 clips one at a time is eight minutes of waiting. Instead N actors stand side by side
on a known grid, each playing a different clip, and since the camera is fixed and the
spacing is known, each actor owns a fixed VERTICAL BAND of the frame. Crop the bands and
they become rows. Six clips per launch keeps a body ~210px wide, which is enough to see
a bent knee.

⛔ REVA_SHOT is what ARMS a capture (SHOTN/SHOTEVERY only say how many and how often),
and the engine never exits once its quota is met -- poll for the frames, then kill it.
"""
import argparse, glob, math, os, shutil, subprocess, sys, time

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
NATIVE = os.path.join(ROOT, "reva_native")

# every clip in v1_zmoves, in the order the film needs them
CLIPS = ["z_walk_a", "z_walk_b", "z_walk_c", "z_run",
         "z_idle_a", "z_idle_b",
         "z_atk_a", "z_atk_b", "z_atk_c", "z_atk_d",
         "z_crawl_a", "z_crawl_b", "z_lay_a", "z_lay_b",
         "z_hit_a", "z_hit_b", "z_hit_c", "z_hit_d", "z_hit_e", "z_hit_f",
         "z_imp_a", "z_imp_b",
         "z_burst_a", "z_burst_b", "z_burst_c", "z_burst_d", "z_burst_e",
         "z_burst_f", "z_burst_g", "z_burst_h", "z_burst_i", "z_burst_k"]

PER = 6            # actors per launch
GAP = 3.6          # the casting-sheet spacing


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--body", default="v1_Character_01")
    ap.add_argument("--secs", type=float, default=3.0)
    ap.add_argument("--fps", type=int, default=30)
    ap.add_argument("--start", type=int, default=420, help="boot costs ~250 frames")
    ap.add_argument("--cols", type=int, default=6)
    ap.add_argument("--clips", default="", help="comma list; default is all 32")
    ap.add_argument("--tile", type=int, default=190)
    ap.add_argument("--out", default=os.path.join(NATIVE, "anim_bench", "zombiecheck.png"))
    a = ap.parse_args()
    from PIL import Image, ImageDraw

    clips = [c for c in a.clips.split(",") if c] or CLIPS
    frames = int(a.secs * a.fps)
    every = max(1, frames // a.cols)
    tmp = os.path.join(NATIVE, "anim_bench", "_zomb")
    rows = []

    for g0 in range(0, len(clips), PER):
        grp = clips[g0:g0 + PER]
        # the set: one actor per clip, in a line, all in place
        span = GAP * (len(grp) - 1)
        cx = span / 2.0
        lines = ["# generated by zombiecheck.py -- do not edit",
                 "prop road_01   %.2f 0.00 14 0 4.0" % (cx - 14)]
        for i, c in enumerate(grp):
            lines.append("actor %s  %s  %.2f 0 0  180  1.0  1.0  0.0  0" % (a.body, c, i * GAP))
        sp = os.path.join(NATIVE, "sets", "_zcheck.set")
        open(sp, "w").write("\n".join(lines) + "\n")

        shutil.rmtree(tmp, ignore_errors=True)
        os.makedirs(tmp, exist_ok=True)
        # Frame the line exactly: at distance d the visible half-width is
        # d*tan(vfov/2)*W/H, so solve d for the half-width the actors actually need.
        # ⛔ Guessing this is what produced the first sheet: the actors filled the middle
        # third of the frame, the crop bands assumed they filled all of it, and every row
        # came back holding two half-bodies or none.
        VFOV, ASPECT = 40.0, 1280.0 / 720.0
        thv = math.tan(math.radians(VFOV) / 2.0)
        need = span / 2.0 + GAP * 0.62          # half the line, plus a body's margin
        dist = need / (thv * ASPECT)
        cam = "%g,2.35,%g,%g,1.35,0,%g" % (cx, -dist, cx, VFOV)
        ctl = os.path.join(NATIVE, "anim_bench", "lab_ctl.txt")
        open(ctl, "w").write(
            "seq=%d face=0 grid=0 dqs=0 clip=z_upright set=_zcheck "
            "sun=52,205,1.25,1.0,0.96,0.90 sky=0.44,0.50,0.62 cam=%s\n"
            % (int(time.time() * 7) % 100000, cam))
        env = dict(os.environ, REVA_WINDOWED="1", REVA_LABCTL="anim_bench/lab_ctl.txt",
                   REVA_AUTOMODE="11", REVA_ANIMSUBJ="r2moves", REVA_ANIMSTATE="0",
                   REVA_FIXEDSTEP=str(a.fps),
                   REVA_SHOT=str(a.start), REVA_SHOTN=str(a.cols),
                   REVA_SHOTEVERY=str(every),
                   REVA_SHOT_PATH=os.path.join(tmp, "f.ppm").replace("/", "\\"))
        pr = subprocess.Popen([os.path.join(NATIVE, "crowd_new.exe"), "400", "packs", "r2moves"],
                              cwd=NATIVE, env=env,
                              stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        got = []
        for _ in range(90):
            got = sorted(glob.glob(os.path.join(tmp, "*.ppm")))
            if len(got) >= a.cols:
                break
            if pr.poll() is not None:
                break
            time.sleep(1)
        time.sleep(0.6)
        pr.kill()
        got = sorted(glob.glob(os.path.join(tmp, "*.ppm")))
        print("  %-40s %d frames" % ("+".join(grp), len(got)))
        if not got:
            for c in grp:
                rows.append((c, []))
            continue

        # ⛔ CROP BY THE ACTUAL PROJECTION, not by an approximation of it. The first two
        # attempts here both put the wrong body in the row -- once by assuming the actors
        # filled the frame's width, once by ignoring the camera's downward tilt -- and the
        # sheet then reported clips as broken that a FULL FRAME showed were perfect. An
        # instrument that lies is worse than none: project the actor's feet and head
        # through the same look-at the engine used, and crop what that says.
        ims = [Image.open(f).convert("RGB") for f in got[:a.cols]]
        W, H = ims[0].size
        eye = (cx, 2.35, -dist)
        aim = (cx, 1.35, 0.0)

        def project(p):
            f = [aim[k] - eye[k] for k in range(3)]
            n = math.sqrt(sum(v * v for v in f)) or 1.0
            f = [v / n for v in f]
            r = [-f[2], 0.0, f[0]]                           # right = forward x (0,1,0)
            n = math.sqrt(sum(v * v for v in r)) or 1.0
            r = [v / n for v in r]
            u = [r[1] * f[2] - r[2] * f[1], r[2] * f[0] - r[0] * f[2],
                 r[0] * f[1] - r[1] * f[0]]
            d = [p[k] - eye[k] for k in range(3)]
            zc = sum(d[k] * f[k] for k in range(3)) or 1e-6
            xc = sum(d[k] * r[k] for k in range(3))
            yc = sum(d[k] * u[k] for k in range(3))
            sx = W / 2.0 + (xc / (zc * thv * ASPECT)) * (W / 2.0)
            sy = H / 2.0 - (yc / (zc * thv)) * (H / 2.0)
            return sx, sy

        for i, c in enumerate(grp):
            x = i * GAP
            fx, fy = project((x, 0.0, 0.0))      # the ground under this actor
            hx, hy = project((x, 3.15, 0.0))     # the top of a club-scale body
            cy = (fy + hy) / 2.0
            # a portrait cell: tall enough for a standing body, wide enough that a body
            # lying on the ground still fits end to end
            hh = abs(fy - hy) * 0.62
            hw = hh * 0.85
            cells = []
            for im in ims:
                box = (int(fx - hw), int(cy - hh), int(fx + hw), int(cy + hh))
                cells.append(im.crop(box).resize((a.tile, int(a.tile * hh / hw)),
                                                 Image.LANCZOS))
            rows.append((c, cells))

    if not rows:
        sys.exit("no frames captured")
    lab = 74
    th = max((c.height for _, cs in rows for c in cs), default=a.tile)
    sheet = Image.new("RGB", (lab + a.cols * a.tile, len(rows) * th), (14, 14, 16))
    d = ImageDraw.Draw(sheet)
    for r, (name, cells) in enumerate(rows):
        d.text((6, r * th + th // 2 - 4), name, fill=(120, 230, 140))
        for c, im in enumerate(cells[:a.cols]):
            sheet.paste(im, (lab + c * a.tile, r * th))
        d.line([(0, r * th), (sheet.width, r * th)], fill=(60, 60, 66))
    sheet.save(a.out)
    print("wrote %s  (%d clips x %d frames)" % (a.out, len(rows), a.cols))


if __name__ == "__main__":
    main()
